// The picture host for the menu photos (from IMAGEKIT_URL_ENDPOINT in .env)
const imageKitHost = (() => {
  try {
    return new URL(process.env.IMAGEKIT_URL_ENDPOINT).hostname;
  } catch {
    return 'ik.imagekit.io';
  }
})();

/** @type {import('next').NextConfig} */
const nextConfig = {
  /* config options here */
  experimental: {
    agentFeedback: true,
  },
  images: {
    remotePatterns: [
      {
        protocol: 'https',
        hostname: 'images.unsplash.com',
      },
      {
        protocol: 'https',
        hostname: imageKitHost,
      },
    ],
  },
  allowedDevOrigins: ['192.168.1.8'],
  cacheComponents: true,
  // Basic browser protections for every page.
  async headers() {
    const isProd = process.env.NODE_ENV === 'production';
    return [
      {
        source: '/:path*',
        headers: [
          { key: 'X-Content-Type-Options', value: 'nosniff' },
          { key: 'X-Frame-Options', value: 'DENY' }, // nobody can show our site inside their page (clickjacking)
          { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
          { key: 'Permissions-Policy', value: 'camera=(), microphone=(), geolocation=()' },
          ...(isProd ? [{ key: 'Strict-Transport-Security', value: 'max-age=63072000; includeSubDomains' }] : []),
        ],
      },
    ];
  },
  partialPrefetching: true,
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
};

export default nextConfig;